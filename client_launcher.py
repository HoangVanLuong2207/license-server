"""License-gated launcher for the shipped AutoTruyenLua_Vua application.

The server keeps the Ed25519 private key. This client contains only the
matching public key and verifies the short-lived token returned by /api/verify.
"""

from __future__ import annotations

import base64
import configparser
import hashlib
import json
import os
from pathlib import Path
import platform
import secrets
import subprocess
import sys
import threading
import time
import tkinter as tk
from tkinter import messagebox, ttk
import urllib.error
import urllib.request

from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey
from cryptography.exceptions import InvalidSignature


PRODUCT_NAME = "ToolAOV"
DEFAULT_SERVER_URL = "http://127.0.0.1:8000"
EXPECTED_SIGNING_KEY_FINGERPRINT = "E7D226490FCF2118"
ORIGINAL_EXE_NAME = "AutoTruyenLua_Vua.exe"


def _b64url_decode(value: str) -> bytes:
    return base64.urlsafe_b64decode(value + "=" * (-len(value) % 4))


def _read_machine_guid() -> str:
    if os.name == "nt":
        try:
            import winreg

            with winreg.OpenKey(
                winreg.HKEY_LOCAL_MACHINE,
                r"SOFTWARE\Microsoft\Cryptography",
            ) as key:
                value, _ = winreg.QueryValueEx(key, "MachineGuid")
                if value:
                    return str(value)
        except OSError:
            pass
    return ""


def get_hwid() -> str:
    """Return a stable, non-reversible identifier for this installation."""
    parts = [
        _read_machine_guid(),
        platform.node(),
        platform.machine(),
        str(os.environ.get("PROCESSOR_IDENTIFIER", "")),
    ]
    raw = "|".join(part for part in parts if part).encode("utf-8")
    return hashlib.sha256(raw).hexdigest()


def _config_path() -> Path:
    external = Path(sys.executable if getattr(sys, "frozen", False) else __file__).with_name(
        "license-client.ini"
    )
    if external.exists():
        return external
    internal_root = getattr(sys, "_MEIPASS", "")
    if internal_root:
        internal = Path(internal_root) / "license-client.ini"
        if internal.exists():
            return internal
    return external


def get_server_url() -> str:
    parser = configparser.ConfigParser()
    path = _config_path()
    if path.exists():
        # The bundled INI is generated by PowerShell and may contain a UTF-8
        # BOM. utf-8-sig accepts both BOM and BOM-less files.
        parser.read(path, encoding="utf-8-sig")
    return parser.get("license", "server_url", fallback=DEFAULT_SERVER_URL).rstrip("/")


def _get_pinned_public_key(server_url: str) -> str:
    request = urllib.request.Request(
        f"{server_url}/ping",
        headers={"Accept": "application/json"},
        method="GET",
    )
    with urllib.request.urlopen(request, timeout=15) as response:
        health = json.loads(response.read().decode("utf-8"))
    public_key_b64 = str(health.get("signing_public_key") or "").strip()
    public_key = base64.b64decode(public_key_b64, validate=True)
    fingerprint = hashlib.sha256(public_key).hexdigest()[:16].upper()
    if fingerprint != EXPECTED_SIGNING_KEY_FINGERPRINT:
        raise ValueError("License server dùng signing key không đúng fingerprint")
    return public_key_b64


def verify_license(server_url: str, key: str) -> tuple[bool, str, dict]:
    hwid = get_hwid()
    nonce = secrets.token_urlsafe(24)
    body = json.dumps({"key": key.strip(), "hwid": hwid, "nonce": nonce}).encode("utf-8")
    request = urllib.request.Request(
        f"{server_url}/api/verify",
        data=body,
        headers={"Content-Type": "application/json", "Accept": "application/json"},
        method="POST",
    )
    try:
        with urllib.request.urlopen(request, timeout=15) as response:
            result = json.loads(response.read().decode("utf-8"))
    except (urllib.error.URLError, TimeoutError, OSError, json.JSONDecodeError) as exc:
        return False, f"Không thể kết nối license server: {exc}", {}

    if not result.get("valid"):
        return False, str(result.get("message") or "Key không hợp lệ"), result

    token = result.get("token", "")
    try:
        encoded, signature = token.split(".", 1)
        public_key_b64 = str(result.get("signing_public_key") or "").strip()
        if not public_key_b64:
            public_key_b64 = _get_pinned_public_key(server_url)
        public_bytes = base64.b64decode(public_key_b64, validate=True)
        fingerprint = hashlib.sha256(public_bytes).hexdigest()[:16].upper()
        if fingerprint != EXPECTED_SIGNING_KEY_FINGERPRINT:
            return False, "Chữ ký máy chủ không khớp cấu hình ứng dụng", result
        public_key = Ed25519PublicKey.from_public_bytes(public_bytes)
        public_key.verify(_b64url_decode(signature), encoded.encode("ascii"))
        claims = json.loads(_b64url_decode(encoded).decode("utf-8"))
    except (InvalidSignature, ValueError, KeyError, TypeError, json.JSONDecodeError) as exc:
        return False, f"Token license không hợp lệ: {exc}", result

    expected_hash = hashlib.sha256(key.strip().encode("utf-8")).hexdigest()
    if claims.get("product") != PRODUCT_NAME:
        return False, "Token không thuộc sản phẩm này", result
    if claims.get("key_hash") != expected_hash:
        return False, "Token không khớp key", result
    if claims.get("hwid") != hwid or claims.get("nonce") != nonce:
        return False, "Token không khớp thiết bị hoặc phiên xác thực", result
    if int(claims.get("exp", 0)) <= int(time.time()):
        return False, "Token license đã hết hạn", result
    return True, "Xác thực license thành công", result


def find_original() -> Path:
    # In a one-file PyInstaller build, the original application is bundled as
    # an internal binary and is available only in the private _MEIPASS folder.
    if getattr(sys, "frozen", False):
        bundled = Path(getattr(sys, "_MEIPASS", "")) / ORIGINAL_EXE_NAME
        if bundled.is_file():
            return bundled
    # Development fallback: allow running the launcher from the source tree.
    candidate = Path(__file__).resolve().parent / ORIGINAL_EXE_NAME
    if candidate.is_file():
        return candidate
    raise FileNotFoundError(f"Không tìm thấy payload nội bộ {ORIGINAL_EXE_NAME}")


class Launcher(tk.Tk):
    def __init__(self) -> None:
        super().__init__()
        self.title("License — AutoTruyenLua Vua")
        self.resizable(False, False)
        self.configure(padx=18, pady=18)
        self.key_var = tk.StringVar()
        self.status_var = tk.StringVar(value="Nhập license key để tiếp tục")
        self.verify_button: ttk.Button | None = None
        self._build_ui()

    def _build_ui(self) -> None:
        ttk.Label(self, text="AUTO TRUYỀN LỬA", font=("Segoe UI", 16, "bold")).grid(
            row=0, column=0, columnspan=2, sticky="w", pady=(0, 4)
        )
        ttk.Label(self, text="Xác thực license trước khi khởi chạy ứng dụng").grid(
            row=1, column=0, columnspan=2, sticky="w", pady=(0, 14)
        )
        ttk.Label(self, text="License key:").grid(row=2, column=0, sticky="w")
        entry = ttk.Entry(self, textvariable=self.key_var, width=42)
        entry.grid(row=3, column=0, columnspan=2, sticky="ew", pady=(4, 12))
        entry.focus_set()
        self.verify_button = ttk.Button(self, text="Xác thực và mở ứng dụng", command=self._on_verify)
        self.verify_button.grid(
            row=4, column=0, columnspan=2, sticky="ew"
        )
        ttk.Label(self, textvariable=self.status_var, foreground="#555", wraplength=360).grid(
            row=5, column=0, columnspan=2, sticky="w", pady=(12, 0)
        )

    def _on_verify(self) -> None:
        key = self.key_var.get().strip()
        if not key:
            messagebox.showwarning("Thiếu key", "Vui lòng nhập license key.")
            return
        self.status_var.set("Đang xác thực...")
        self.update_idletasks()
        if self.verify_button is not None:
            self.verify_button.configure(state="disabled")
        threading.Thread(target=self._verify_worker, args=(key,), daemon=True).start()

    def _verify_worker(self, key: str) -> None:
        try:
            result = verify_license(get_server_url(), key)
            self.after(0, self._finish_verify, result)
        except Exception as exc:
            self.after(0, self._finish_verify, (False, f"Lỗi xác thực: {exc}", {}))

    def _finish_verify(self, verification: tuple[bool, str, dict]) -> None:
        ok, message, result = verification
        if not ok:
            self.status_var.set(message)
            if self.verify_button is not None:
                self.verify_button.configure(state="normal")
            messagebox.showerror("License không hợp lệ", message)
            return
        try:
            original = find_original()
            subprocess.Popen([str(original)], cwd=str(original.parent))
            self.status_var.set(
                f"Đã xác thực. Hạn sử dụng: {result.get('expires') or 'vĩnh viễn'}"
            )
            self.after(500, self.destroy)
        except FileNotFoundError as exc:
            self.status_var.set(str(exc))
            if self.verify_button is not None:
                self.verify_button.configure(state="normal")
            messagebox.showerror("Thiếu payload", str(exc))
        except OSError as exc:
            self.status_var.set(f"Không thể khởi chạy: {exc}")
            if self.verify_button is not None:
                self.verify_button.configure(state="normal")
            messagebox.showerror("Lỗi khởi chạy", str(exc))


if __name__ == "__main__":
    Launcher().mainloop()
